def values_match(actual, expected):
    if isinstance(expected, float):
        return math.isclose(
            float(actual),
            expected,
            rel_tol=0.0,
            abs_tol=1e-9,
        )

    return actual == expected


def validate_final_configuration(metrics_df, metrics_csv):
    row = metrics_df.iloc[0]
    expected_values = {
        "Configuration": CONFIGURATION_NAME,
        "Gaussian Kernel": GAUSSIAN_KERNEL,
        "Gaussian Sigma": GAUSSIAN_SIGMA,
        "LBP Points": LBP_POINTS,
        "LBP Radius": LBP_RADIUS,
        "LBP Weight": LBP_WEIGHT,
        "Gaussian Weight": GAUSSIAN_WEIGHT,
    }

    for column, expected in expected_values.items():
        if column not in metrics_df.columns:
            raise ValueError(
                f"Missing configuration column in {metrics_csv.name}: "
                f"{column}"
            )

        actual = row[column]

        if not values_match(actual, expected):
            raise ValueError(
                f"Final configuration mismatch for {column}: "
                f"expected {expected}, found {actual}."
            )


def read_yolo_metrics(metrics_csv):
    if not metrics_csv.exists():
        raise FileNotFoundError(
            f"Could not find final test metrics:\n{metrics_csv}\n"
            "Run test_gaussian_lbp_final_model.py first or provide "
            "--metrics-csv."
        )

    metrics_df = pd.read_csv(metrics_csv)

    if metrics_df.empty:
        raise ValueError("The overall test metrics CSV is empty.")

    required_columns = [
        "YOLO Preprocess Time (ms/image)",
        "Inference Time (ms/image)",
        "Postprocess Time (ms/image)",
        "Total YOLO Time (ms/image)",
        "mAP50-95",
    ]
    missing_columns = [
        column
        for column in required_columns
        if column not in metrics_df.columns
    ]

    if missing_columns:
        raise ValueError(
            f"Missing columns in {metrics_csv.name}: {missing_columns}"
        )

    validate_final_configuration(metrics_df, metrics_csv)
    row = metrics_df.iloc[0]

    return {
        "YOLO Preprocess Time (ms/image)": float(
            row["YOLO Preprocess Time (ms/image)"]
        ),
        "Inference Time (ms/image)": float(
            row["Inference Time (ms/image)"]
        ),
        "Postprocess Time (ms/image)": float(
            row["Postprocess Time (ms/image)"]
        ),
        "Total YOLO Time (ms/image)": float(
            row["Total YOLO Time (ms/image)"]
        ),
        "mAP50-95": float(row["mAP50-95"]),
    }


# ============================================================
# CREATE SUMMARY
# ============================================================

def create_summary(
    timing_df,
    number_of_test_images,
    yolo_metrics,
):
    preprocessing_times = timing_df["Preprocessing Time (ms)"]
    average_preprocessing = preprocessing_times.mean()
    median_preprocessing = preprocessing_times.median()
    std_preprocessing = preprocessing_times.std()
    minimum_preprocessing = preprocessing_times.min()
    maximum_preprocessing = preprocessing_times.max()

    # The custom enhancement was performed offline when the dataset was
    # generated. It is therefore not included in Ultralytics' reported
    # YOLO preprocessing time and must be added separately.
    total_pipeline_time = (
        average_preprocessing
        + yolo_metrics["Total YOLO Time (ms/image)"]
    )
    estimated_fps = 1000 / total_pipeline_time

    return pd.DataFrame(
        [
            {
                "Technique": TECHNIQUE_NAME,
                "Configuration": CONFIGURATION_NAME,
                "Number of Test Images": number_of_test_images,
                "Timing Repeats": REPEATS,
                "Warm-up Images": min(
                    WARMUP_IMAGES,
                    number_of_test_images,
                ),
                "Gaussian Kernel": GAUSSIAN_KERNEL,
                "Gaussian Sigma": GAUSSIAN_SIGMA,
                "LBP Points": LBP_POINTS,
                "LBP Radius": LBP_RADIUS,
                "LBP Weight": LBP_WEIGHT,
                "Gaussian Weight": GAUSSIAN_WEIGHT,
                "Average Custom Preprocessing Time (ms/image)": (
                    average_preprocessing
                ),
                "Median Custom Preprocessing Time (ms/image)": (
                    median_preprocessing
                ),
                "Std Custom Preprocessing Time (ms/image)": (
                    std_preprocessing
                ),
                "Minimum Custom Preprocessing Time (ms/image)": (
                    minimum_preprocessing
                ),
                "Maximum Custom Preprocessing Time (ms/image)": (
                    maximum_preprocessing
                ),
                "YOLO Preprocess Time (ms/image)": yolo_metrics[
                    "YOLO Preprocess Time (ms/image)"
                ],
                "YOLO Inference Time (ms/image)": yolo_metrics[
                    "Inference Time (ms/image)"
                ],
                "YOLO Postprocess Time (ms/image)": yolo_metrics[
                    "Postprocess Time (ms/image)"
                ],
                "Total YOLO Time (ms/image)": yolo_metrics[
                    "Total YOLO Time (ms/image)"
                ],
                "Estimated Total Pipeline Time (ms/image)": (
                    total_pipeline_time
                ),
                "Estimated Pipeline FPS": estimated_fps,
                "Final Test mAP50-95": yolo_metrics["mAP50-95"],
            }
        ]
    )


