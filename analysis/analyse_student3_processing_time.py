# MAIN
# ============================================================

def main():
    args = parse_arguments()
    dataset_root = args.dataset_root.expanduser().resolve()
    metrics_csv = args.metrics_csv.expanduser().resolve()
    output_dir = args.output.expanduser().resolve()

    print()
    print("=" * 80)
    print("G2-L1-W1 GAUSSIAN + LBP PROCESSING TIME ANALYSIS")
    print("=" * 80)
    print(f"Original dataset : {dataset_root}")
    print(f"Final metrics    : {metrics_csv}")
    print(f"Output directory: {output_dir}")
    print(f"Gaussian kernel  : {GAUSSIAN_KERNEL}")
    print(f"Gaussian sigma   : {GAUSSIAN_SIGMA}")
    print(f"LBP points       : {LBP_POINTS}")
    print(f"LBP radius       : {LBP_RADIUS}")
    print(f"LBP weight       : {LBP_WEIGHT}")
    print(f"Gaussian weight  : {GAUSSIAN_WEIGHT}")

    test_directory = find_test_images_directory(dataset_root)
    image_paths = get_test_images(test_directory)
    print(f"\nTest image directory:\n{test_directory}")
    print(f"\nNumber of test images found: {len(image_paths)}")

    warm_up(image_paths)
    timing_df = measure_preprocessing_time(image_paths)
    yolo_metrics = read_yolo_metrics(metrics_csv)
    summary_df = create_summary(
        timing_df,
        len(image_paths),
        yolo_metrics,
    )
    per_image_path, summary_path = save_results(
        timing_df,
        summary_df,
        output_dir,
    )
    print_summary(summary_df)

    print("\n" + "=" * 80)
    print("FILES GENERATED")
    print("=" * 80)
    print(f"\nPer-image timing:\n{per_image_path}")
    print(f"\nSummary:\n{summary_path}")


if __name__ == "__main__":
    main()
