def save_results(timing_df, summary_df, output_dir):
    output_dir.mkdir(parents=True, exist_ok=True)
    per_image_path = (
        output_dir
        / "student3_preprocessing_per_image.csv"
    )
    summary_path = (
        output_dir
        / "student3_processing_time_summary.csv"
    )

    timing_df.to_csv(per_image_path, index=False)
    summary_df.to_csv(summary_path, index=False)
    return per_image_path, summary_path


