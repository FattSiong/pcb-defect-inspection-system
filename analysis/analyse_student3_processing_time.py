if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from preprocessing.gaussian_lbp import enhance_gaussian_lbp


DEFAULT_DATASET_ROOT = (
    Path.home()
    / "Downloads"
    / "pcb_dataset_reduced"
)

DEFAULT_OVERALL_METRICS_CSV = (
    PROJECT_ROOT
    / "runs"
    / "gaussian_lbp_final_test"
    / "fusion_test"
    / "overall_test_metrics.csv"
)

DEFAULT_OUTPUT_DIR = (
    PROJECT_ROOT
    / "results"
    / "processing_time"
)


# ============================================================
# FINAL G2-L1-W1 PARAMETERS
# ============================================================

GAUSSIAN_KERNEL = 3
GAUSSIAN_SIGMA = 0.8
LBP_POINTS = 8
LBP_RADIUS = 1.0
LBP_WEIGHT = 0.15
GAUSSIAN_WEIGHT = 1.0 - LBP_WEIGHT

TECHNIQUE_NAME = (
    "Gaussian Filtering + Uniform LBP Luminance Fusion"
)
CONFIGURATION_NAME = "G2-L1-W1"


# ============================================================
# TIMING SETTINGS
# Keep these equal to the other processing-time scripts.
# ============================================================

REPEATS = 3
WARMUP_IMAGES = 20

IMAGE_EXTENSIONS = {
    ".jpg",
    ".jpeg",
    ".png",
    ".bmp",
    ".tif",
    ".tiff",
    ".webp",
}


# ============================================================
# COMMAND-LINE ARGUMENTS
# ============================================================

def parse_arguments():
    parser = ArgumentParser(
        description=(
            "Measure G2-L1-W1 custom preprocessing time and combine it "
            "with saved YOLO test timing."
        )
    )
    parser.add_argument(
        "--dataset-root",
        type=Path,
        default=DEFAULT_DATASET_ROOT,
        help=(
            "Root of the original, unprocessed YOLO dataset. Default: "
            f"{DEFAULT_DATASET_ROOT}"
        ),
    )
    parser.add_argument(
        "--metrics-csv",
        type=Path,
        default=DEFAULT_OVERALL_METRICS_CSV,
        help=(
            "overall_test_metrics.csv generated by the G2-L1-W1 final "
            f"test. Default: {DEFAULT_OVERALL_METRICS_CSV}"
        ),
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT_DIR,
        help=(
            "Directory for per-image timing and summary CSV files. "
            f"Default: {DEFAULT_OUTPUT_DIR}"
        ),
    )
    return parser.parse_args()


# ============================================================
# FIND TEST IMAGES
# ============================================================

def find_test_images_directory(dataset_root):
    possible_directories = [
        dataset_root / "test" / "images",
        dataset_root / "test",
    ]

    for directory in possible_directories:
        if not directory.exists():
            continue

        image_files = [
            path
            for path in directory.rglob("*")
            if (
                path.is_file()
                and path.suffix.lower() in IMAGE_EXTENSIONS
            )
        ]

        if image_files:
            return directory

    raise FileNotFoundError(
        "Could not find the original test images. "
        f"Checked under:\n{dataset_root}"
    )


def get_test_images(test_directory):
    image_paths = sorted(
        path
        for path in test_directory.rglob("*")
        if (
            path.is_file()
            and path.suffix.lower() in IMAGE_EXTENSIONS
        )
    )

    if not image_paths:
        raise FileNotFoundError("No test images were found.")

    return image_paths


# ============================================================
# G2-L1-W1 PREPROCESSING
# ============================================================

def apply_gaussian_lbp(image):
    return enhance_gaussian_lbp(
        image,
        gaussian_kernel=GAUSSIAN_KERNEL,
        gaussian_sigma=GAUSSIAN_SIGMA,
        lbp_points=LBP_POINTS,
        lbp_radius=LBP_RADIUS,
        lbp_weight=LBP_WEIGHT,
    )


# ============================================================
# WARM-UP
# ============================================================

def warm_up(image_paths):
    number_of_warmup_images = min(
        WARMUP_IMAGES,
        len(image_paths),
    )

    print(
        f"\nWarming up with {number_of_warmup_images} images..."
    )
    warmed_up = 0

    for image_path in image_paths[:number_of_warmup_images]:
        image = cv2.imread(str(image_path), cv2.IMREAD_COLOR)

        if image is None:
            print(f"Warning: Could not read {image_path}")
            continue

        _ = apply_gaussian_lbp(image)
        warmed_up += 1

    if warmed_up == 0:
        raise RuntimeError("No images could be read during warm-up.")


# ============================================================
# MEASURE CUSTOM PREPROCESSING TIME
# ============================================================

def measure_preprocessing_time(image_paths):
    timing_records = []

    print()
    print("=" * 80)
    print("MEASURING G2-L1-W1 CUSTOM PREPROCESSING TIME")
    print("=" * 80)

    for repeat in range(1, REPEATS + 1):
        print(f"\nRepeat {repeat}/{REPEATS}")

        for image_number, image_path in enumerate(
            image_paths,
            start=1,
        ):
            # Image loading is deliberately excluded from preprocessing
            # time, matching the other processing-time scripts.
            image = cv2.imread(str(image_path), cv2.IMREAD_COLOR)

            if image is None:
                print(f"Warning: Could not read {image_path}")
                continue

            start_time = time.perf_counter_ns()
            _ = apply_gaussian_lbp(image)
            end_time = time.perf_counter_ns()

            preprocessing_time_ms = (
                end_time - start_time
            ) / 1_000_000

            timing_records.append(
                {
                    "Repeat": repeat,
                    "Image": image_path.name,
                    "Preprocessing Time (ms)": preprocessing_time_ms,
                }
            )

            if (
                image_number % 100 == 0
                or image_number == len(image_paths)
            ):
                print(
                    f"  Processed {image_number}/"
                    f"{len(image_paths)} images"
                )

    if not timing_records:
        raise RuntimeError("No images were successfully timed.")

    return pd.DataFrame(timing_records)


