"""Train and validate YOLOv8n on one Gaussian-LBP dataset."""

from argparse import ArgumentParser
from pathlib import Path
import csv
import json
import time

import torch
from ultralytics import YOLO


# =========================================================
# MODEL AND OUTPUT PATHS
# =========================================================

PROJECT_ROOT = Path(__file__).resolve().parents[1]
MODEL_PATH = PROJECT_ROOT / "yolov8n.pt"
DEFAULT_RUNS_ROOT = PROJECT_ROOT / "runs" / "gaussian_lbp"


# =========================================================
# FIXED YOLO SETTINGS
# Same settings as train_student1_blocksize.py
# =========================================================

EPOCHS = 100
IMAGE_SIZE = 640
TRAIN_BATCH_SIZE = -1
VAL_BATCH_SIZE = 4
DEVICE = 0
SEED = 42
PATIENCE = 150


def parse_arguments():
    parser = ArgumentParser(
        description=(
            "Train YOLOv8n on a generated Gaussian-LBP dataset "
            "and validate its best checkpoint."
        )
    )
    parser.add_argument(
        "--data",
        type=Path,
        required=True,
        help="Path to the generated dataset data.yaml.",
    )
    parser.add_argument(
        "--name",
        default="single_scale_s1",
        help="Experiment name inside the runs directory.",
    )
    parser.add_argument(
        "--project",
        type=Path,
        default=DEFAULT_RUNS_ROOT,
        help="Directory in which Ultralytics saves the runs.",
    )
    return parser.parse_args()


def check_environment(data_yaml):
    print("=" * 80)
    print("GAUSSIAN + SINGLE-SCALE LBP YOLO TRAINING")
    print("=" * 80)

    if not MODEL_PATH.exists():
        raise FileNotFoundError(
            f"YOLOv8n checkpoint not found: {MODEL_PATH}"
        )

    if not data_yaml.exists():
        raise FileNotFoundError(
            f"Dataset YAML not found: {data_yaml}\n"
            "Run build_gaussian_lbp_dataset.py first."
        )

    processing_config = data_yaml.parent / "processing_config.json"

    if not processing_config.exists():
        raise FileNotFoundError(
            "Gaussian-LBP processing configuration not found: "
            f"{processing_config}"
        )

    configuration = json.loads(
        processing_config.read_text(encoding="utf-8")
    )

    if configuration.get("method") != (
        "gaussian_uniform_lbp_luminance_fusion"
    ):
        raise RuntimeError(
            "The selected dataset was not generated by the "
            "Gaussian-LBP dataset builder."
        )

    generated_splits = configuration.get("splits", [])

    if "train" not in generated_splits or "val" not in generated_splits:
        raise RuntimeError(
            "The generated dataset must contain train and val splits."
        )

    if not torch.cuda.is_available():
        raise RuntimeError("CUDA is not available.")

    print(f"GPU             : {torch.cuda.get_device_name(DEVICE)}")
    print(f"Model           : {MODEL_PATH}")
    print(f"Dataset         : {data_yaml}")
    print(f"Epochs          : {EPOCHS}")
    print(f"Image size      : {IMAGE_SIZE}")
    print(f"Training batch  : {TRAIN_BATCH_SIZE}")
    print(f"Validation batch: {VAL_BATCH_SIZE}")
    print(f"Device          : {DEVICE}")
    print(f"Seed            : {SEED}")
    print(f"Patience        : {PATIENCE}")
    print(
        "Preprocessing   : "
        f"{json.dumps(configuration, indent=2)}"
    )


def train_model(data_yaml, runs_root, experiment_name):
    print()
    print("=" * 80)
    print(f"TRAINING: {experiment_name}")
    print("=" * 80)

    # Always start from a fresh copy of the same pretrained checkpoint.
    model = YOLO(str(MODEL_PATH))
    start_time = time.time()

    model.train(
        data=str(data_yaml),
        epochs=EPOCHS,
        imgsz=IMAGE_SIZE,
        batch=TRAIN_BATCH_SIZE,
        device=DEVICE,
        seed=SEED,
        patience=PATIENCE,
        project=str(runs_root),
        name=experiment_name,
        exist_ok=True,
        plots=True,
    )

    training_time = time.time() - start_time
    best_model = Path(model.trainer.best)

    if not best_model.exists():
        raise FileNotFoundError(
            f"Best model checkpoint was not created: {best_model}"
        )

    print(f"Training time: {training_time:.2f} seconds")
    print(f"Best model   : {best_model}")

    return best_model, training_time


def validate_model(
    data_yaml,
    runs_root,
    experiment_name,
    best_model,
    training_time,
):
    print()
    print("-" * 80)
    print(f"VALIDATING: {experiment_name}")
    print("-" * 80)

    model = YOLO(str(best_model))
    metrics = model.val(
        data=str(data_yaml),
        split="val",
        imgsz=IMAGE_SIZE,
        batch=VAL_BATCH_SIZE,
        device=DEVICE,
        project=str(runs_root),
        name=f"{experiment_name}_validation",
        exist_ok=True,
        plots=True,
    )

    precision = float(metrics.box.mp)
    recall = float(metrics.box.mr)
    map50 = float(metrics.box.map50)
    map50_95 = float(metrics.box.map)
    f1_score = (
        2 * precision * recall / (precision + recall)
        if precision + recall > 0
        else 0.0
    )

    result = {
        "Experiment": experiment_name,
        "Dataset": str(data_yaml),
        "Precision": precision,
        "Recall": recall,
        "F1-score": f1_score,
        "mAP50": map50,
        "mAP50-95": map50_95,
        "Training Time (seconds)": training_time,
        "Best Model": str(best_model),
    }

    print(f"Precision : {precision:.4f}")
    print(f"Recall    : {recall:.4f}")
    print(f"F1-score  : {f1_score:.4f}")
    print(f"mAP50     : {map50:.4f}")
    print(f"mAP50-95  : {map50_95:.4f}")

    return result


def save_result(result, runs_root, experiment_name):
    runs_root.mkdir(parents=True, exist_ok=True)
    output_path = runs_root / f"{experiment_name}_metrics.csv"

    with output_path.open(
        "w",
        newline="",
        encoding="utf-8",
    ) as file:
        writer = csv.DictWriter(
            file,
            fieldnames=list(result.keys()),
        )
        writer.writeheader()
        writer.writerow(result)

    print(f"Results saved: {output_path}")


def main():
    args = parse_arguments()
    data_yaml = args.data.resolve()
    runs_root = args.project.resolve()

    if Path(args.name).name != args.name:
        raise ValueError(
            "Experiment name must not contain directory separators."
        )

    check_environment(data_yaml)
    best_model, training_time = train_model(
        data_yaml=data_yaml,
        runs_root=runs_root,
        experiment_name=args.name,
    )
    result = validate_model(
        data_yaml=data_yaml,
        runs_root=runs_root,
        experiment_name=args.name,
        best_model=best_model,
        training_time=training_time,
    )
    save_result(result, runs_root, args.name)


if __name__ == "__main__":
    main()

